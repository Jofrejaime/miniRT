int	ft_atoi(const char *nptr)
{
	int	i;
	int	c;
	int	s;
	int	r;

	i = 0;
	c = 0;
	s = 1;
	r = 0;
	while (nptr[i] == 32 || (nptr[i] >= 9 && nptr[i] <= 13))
		i++;
	while (nptr[i] == '-' || nptr[i] == '+')
	{
		c++;
		if (nptr[i++] == '-')
			s *= -1;
	}
	if (c > 1)
		return (0);
	while (nptr[i] >= '0' && nptr[i] <= '9')
		r = r * 10 + nptr[i++] - 48;
	return (r * s);
}
